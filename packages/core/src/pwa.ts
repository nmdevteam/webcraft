import { z } from 'zod'
import { ColorValueSchema } from './design-system'

const safePwaMediaPath = z.string().max(220).refine((value) => value === '' || /^\/media\/[A-Za-z0-9][A-Za-z0-9._-]{0,150}\.(?:png|jpe?g|webp|gif)$/i.test(value), 'Choose a raster image from this project’s asset library')

export const PwaSettingsSchema = z.object({
  enabled: z.boolean().default(false),
  name: z.string().max(120).default(''),
  shortName: z.string().max(32).default(''),
  icon192Path: safePwaMediaPath.default(''),
  icon512Path: safePwaMediaPath.default(''),
  themeColor: ColorValueSchema.default('#5b5ce2'),
  backgroundColor: ColorValueSchema.default('#ffffff'),
  display: z.enum(['standalone', 'fullscreen', 'minimal-ui', 'browser']).default('standalone'),
  cacheStrategy: z.enum(['network-first', 'cache-first', 'stale-while-revalidate']).default('network-first'),
  offlineFallback: z.boolean().default(true),
}).strict()
export type PwaSettings = z.infer<typeof PwaSettingsSchema>

export function getPwaReadiness(settings: PwaSettings): string[] {
  if (!settings.enabled) return ['PWA output is off; existing exports remain unchanged.']
  const messages: string[] = []
  if (!settings.icon192Path) messages.push('Choose an application icon (192×192 recommended).')
  if (!settings.icon512Path) messages.push('Choose a large application icon (512×512 recommended).')
  if (settings.icon192Path || settings.icon512Path) messages.push('Selected project icons are checked for exact pixel dimensions when settings are saved and again before export.')
  if (!settings.offlineFallback) messages.push('Offline navigation will fall back to the cached site shell; no dedicated offline page will be included.')
  messages.push('Install prompts require a secure deployment origin (HTTPS or localhost); this source check does not simulate a browser install prompt.')
  return messages
}

export function createPwaManifest(settings: PwaSettings) {
  const sizes = new Map<string, string[]>()
  const manifestPath = (path: string) => path.startsWith('/media/') ? `/assets/${path.slice('/media/'.length)}` : path
  if (settings.icon192Path) {
    const path = manifestPath(settings.icon192Path)
    sizes.set(path, [...(sizes.get(path) ?? []), '192x192'])
  }
  if (settings.icon512Path) {
    const path = manifestPath(settings.icon512Path)
    sizes.set(path, [...(sizes.get(path) ?? []), '512x512'])
  }
  return {
    id: '/',
    name: settings.name,
    short_name: settings.shortName,
    start_url: '/',
    scope: '/',
    display: settings.display,
    theme_color: settings.themeColor,
    background_color: settings.backgroundColor,
    icons: [...sizes.entries()].map(([src, iconSizes]) => ({
      src,
      sizes: iconSizes.join(' '),
      type: src.toLowerCase().endsWith('.webp') ? 'image/webp' : src.toLowerCase().endsWith('.jpg') || src.toLowerCase().endsWith('.jpeg') ? 'image/jpeg' : src.toLowerCase().endsWith('.gif') ? 'image/gif' : 'image/png',
      purpose: 'any',
    })),
  }
}

export function generatePwaServiceWorker(cacheStrategy: PwaSettings['cacheStrategy'], offlineFallback: boolean): string {
  const strategy = JSON.stringify(cacheStrategy)
  const offline = JSON.stringify(offlineFallback)
  return `/* Generated by WebCraft. Only same-origin public static GET responses are cached. */
const CACHE_NAME = 'webcraft-pwa-v1';
const CACHE_STRATEGY = ${strategy};
const OFFLINE_FALLBACK = ${offline};
const PRECACHE = ['/', '/manifest.webmanifest', ...(OFFLINE_FALLBACK ? ['/offline.html'] : [])];
const MAX_ENTRIES = 150;
const MAX_RESPONSE_BYTES = 8 * 1024 * 1024;
let cacheWriteQueue = Promise.resolve();

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE_NAME).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (event) => {
  event.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((key) => key.startsWith('webcraft-pwa-') && key !== CACHE_NAME).map((key) => caches.delete(key)))).then(() => self.clients.claim()));
});
async function cacheResponse(request, response) {
  if (!response || response.status !== 200 || response.type !== 'basic' || new URL(request.url).origin !== self.location.origin) return response;
  const cacheControl = response.headers.get('Cache-Control') || '';
  const contentLength = Number(response.headers.get('Content-Length') || 0);
  const vary = response.headers.get('Vary') || '';
  if (/\\b(?:private|no-store)\\b/i.test(cacheControl) || vary.split(',').some((value) => value.trim() === '*') || contentLength > MAX_RESPONSE_BYTES) return response;
  const clone = response.clone();
  const reader = clone.body?.getReader();
  let cacheableResponse = clone;
  if (reader) {
    const chunks = [];
    let size = 0;
    try {
      while (true) {
        const { done, value } = await reader.read();
        if (done) break;
        size += value.byteLength;
        if (size > MAX_RESPONSE_BYTES) { await reader.cancel(); return response; }
        chunks.push(value);
      }
    } catch { return response; }
    const body = new Uint8Array(size);
    let offset = 0;
    for (const chunk of chunks) { body.set(chunk, offset); offset += chunk.byteLength; }
    cacheableResponse = new Response(body, { status: response.status, statusText: response.statusText, headers: response.headers });
  }
  const write = cacheWriteQueue.then(async () => {
    const cache = await caches.open(CACHE_NAME);
    const keys = await cache.keys();
    if (!keys.some((key) => key.url === request.url)) {
      while (keys.length >= MAX_ENTRIES) {
        const oldest = keys.shift();
        if (oldest) await cache.delete(oldest);
      }
    }
    await cache.put(request, cacheableResponse);
    const updatedKeys = await cache.keys();
    while (updatedKeys.length > MAX_ENTRIES) {
      const oldestIndex = updatedKeys.findIndex((key) => key.url !== request.url);
      const [oldest] = updatedKeys.splice(oldestIndex < 0 ? 0 : oldestIndex, 1);
      if (oldest) await cache.delete(oldest);
    }
  });
  cacheWriteQueue = write.catch(() => {});
  await write;
  return response;
}
async function networkFirst(request) {
  try { return await cacheResponse(request, await fetch(request)); }
  catch { return await caches.match(request) || Response.error(); }
}
async function cacheFirst(request) {
  const cached = await caches.match(request);
  if (cached) return cached;
  try { return await cacheResponse(request, await fetch(request)); }
  catch { return Response.error(); }
}
async function staleWhileRevalidate(request) {
  const cached = await caches.match(request);
  const update = fetch(request).then((response) => cacheResponse(request, response)).catch(() => null);
  return cached || await update || Response.error();
}
self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;
  if (!['document', 'script', 'style', 'image', 'font', 'manifest'].includes(request.destination)) return;
  if (request.mode === 'navigate') {
    event.respondWith(fetch(request).then((response) => cacheResponse(request, response)).catch(async () => {
      return await caches.match(request) || (OFFLINE_FALLBACK ? await caches.match('/offline.html') : null) || await caches.match('/') || Response.error();
    }));
    return;
  }
  event.respondWith(CACHE_STRATEGY === 'cache-first' ? cacheFirst(request) : CACHE_STRATEGY === 'stale-while-revalidate' ? staleWhileRevalidate(request) : networkFirst(request));
});
`
}

export function offlineFallbackHtml(appName: string, themeColor = '#ffffff'): string {
  const safeName = appName.replace(/[&<>"']/g, (character) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[character]!)
  const safeTheme = ColorValueSchema.safeParse(themeColor).success ? themeColor : '#ffffff'
  return `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="theme-color" content="${safeTheme}"><title>Offline · ${safeName}</title><style>body{margin:0;min-height:100vh;display:grid;place-items:center;padding:2rem;background:#f5f6fa;color:#25273a;font:16px/1.6 system-ui,sans-serif}main{max-width:34rem;padding:2rem;border:1px solid #e4e6ee;border-radius:1rem;background:#fff}h1{font-size:1.6rem}p{color:#686d80}</style></head><body><main><h1>You’re offline</h1><p>${safeName} could not reach the network. Reconnect and try again.</p></main></body></html>\n`
}
